const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const text = fs.readFileSync(path.join(root, '素材库', '素材预览.html'), 'utf8');
const decode = s => s.replace(/&quot;/g, '"').replace(/&#x27;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const cards = Array.from(text.matchAll(/<article data-search="([^"]*)" data-group="([^"]*)" data-lang="([^"]*)">/g), m => ({ dataset: { search: decode(m[1]), group: decode(m[2]), lang: decode(m[3]) }, hidden: false }));
const nodes = Object.fromEntries(['q', 'group', 'lang', 'count', 'empty'].map(id => [id, { value: '', addEventListener() {} }]));
const sandbox = { document: { querySelectorAll: () => cards, getElementById: id => nodes[id] } };
vm.createContext(sandbox);
vm.runInContext(text.match(/<script>([\s\S]*?)<\/script>/)[1], sandbox);
const visible = () => cards.filter(c => !c.hidden).length;
sandbox.filter(); assert.equal(visible(), 76);
nodes.q.value = 'A020'; sandbox.filter(); assert.equal(visible(), 1);
nodes.q.value = ''; nodes.lang.value = '英文'; sandbox.filter(); assert.equal(visible(), 17);
nodes.q.value = 'D002'; sandbox.filter(); assert.equal(visible(), 8);
nodes.lang.value = '中文'; sandbox.filter(); assert.equal(visible(), 0); assert.equal(nodes.empty.hidden, false);
nodes.q.value = ''; nodes.lang.value = ''; nodes.group.value = 'Yvelise双乳礼盒'; sandbox.filter(); assert.equal(visible(), 10);
nodes.group.value = ''; nodes.q.value = '不存在的素材123'; sandbox.filter(); assert.equal(visible(), 0);
nodes.q.value = ''; sandbox.filter(); assert.equal(visible(), 76);
const reportPath = path.join(root, '整理校验.json');
const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
report.search_logic = 'Node VM执行实际页面脚本：全部/编号/语言/分类/组合/无匹配/清空恢复断言通过；非真实浏览器验证';
fs.writeFileSync(reportPath, JSON.stringify(report, null, 2) + '\n', 'utf8');
console.log(JSON.stringify({ cards: cards.length, search_checks: 'passed', browser: '未验证' }));
